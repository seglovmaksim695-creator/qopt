#!/usr/bin/env python3
"""Build qoptct/foreign/projectq/data/registry.json from results/projectq/*.json.

    python scripts/build_projectq_registry.py            # (re)write the registry
    python scripts/build_projectq_registry.py --check    # exit 1 if the registry on disk differs from a fresh build

An entry is made only for a result that is PROVED, whose canaries all behaved (none PROVED, >= 20 decided, at least half of them
targeted).  Results that are REFUTED are listed under ``findings`` (they say what ProjectQ's own decomposition gets wrong).
Every entry copies its facts from ONE result file; the SHA-256 of the file is in ``evidence``.
"""
import argparse
import glob
import hashlib
import json
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(REPO, 'results', 'projectq')
OUT = os.path.join(REPO, 'qoptct', 'foreign', 'projectq', 'data', 'registry.json')
SCHEMA = 'qoptct.projectq.registry/1'


def _sha(path):
    with open(path, 'rb') as f:
        return hashlib.sha256(f.read()).hexdigest()


def build():
    entries, findings = [], []
    for path in sorted(glob.glob(os.path.join(RES, '*.json'))):
        d = json.load(open(path))
        ev = dict(file=os.path.basename(path), sha256=_sha(path))
        c = d.get('canaries')
        if d['status'] == 'PROVED' and c and c['ok']:
            size = d.get('m', d.get('n'))
            entries.append(dict(
                id=d['id'], name=d['name'], block=d['block'], claim=d['claim'], status='PROVED', size=size, projectq=d['projectq'],
                source=d.get('source'), program=d['program'], recording_sha256=d['recording_sha256'], domain=d.get('domain'),
                garbage=d['garbage'], circuit=d['circuit'],
                canaries=dict(decided=c['decided'], not_proved=c['not_proved'], equivalent=c['equivalent'], by_group=c['by_group']),
                independent=dict(exact_vs_sampled=d.get('independent'), projectq_classical_simulator=d.get('native')),
                assumptions=d['assumptions'], reproduce=d['reproduce'], evidence=ev))
        elif d['status'] == 'REFUTED':
            findings.append(dict(id=d['id'], block=d['block'], claim=d['claim'], status='REFUTED', detail=d['detail'],
                                 projectq=d['projectq'], reproduce=d['reproduce'], evidence=ev))
    return dict(schema=SCHEMA, note='generated by scripts/build_projectq_registry.py from results/projectq/*.json; entries are PROVED only',
                entries=entries, findings=findings)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args(argv)
    text = json.dumps(build(), indent=1, sort_keys=True) + '\n'
    if a.check:
        return 0 if os.path.exists(OUT) and open(OUT).read() == text else 1
    with open(OUT, 'w') as f:
        f.write(text)
    print(f'wrote {OUT}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
